// ── Full Emoji Sheet ──────────────────────────────────────────────────────────

class _FullEmojiSheet extends StatefulWidget {
  final List<Map<String, dynamic>> categories;
  final Function(String emoji) onReactionSelected;

  const _FullEmojiSheet({
    required this.categories,
    required this.onReactionSelected,
  });

  @override
  State<_FullEmojiSheet> createState() => _FullEmojiSheetState();
}

class _FullEmojiSheetState extends State<_FullEmojiSheet> {
  int _selectedCategory = 0;
  late final PageController _pageController;

  @override
  void initState() {
    super.initState();
    _pageController = PageController();
  }

  @override
  void dispose() {
    _pageController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Container(
      height: MediaQuery.of(context).size.height * 0.55,
      decoration: BoxDecoration(
        color: AppColors.navBgColor,
        borderRadius: BorderRadius.vertical(top: Radius.circular(24.r)),
      ),
      child: Column(
        children: [
          // ── Handle ──
          SizedBox(height: 12.h),
          Container(
            width: 40.w,
            height: 4.h,
            decoration: BoxDecoration(
              color: Colors.white24,
              borderRadius: BorderRadius.circular(2.r),
            ),
          ),
          SizedBox(height: 12.h),

          // ── Title ──
          Padding(
            padding: EdgeInsets.symmetric(horizontal: 20.w),
            child: Row(
              children: [
                Text(
                  'Reactions',
                  style: TextStyle(
                    color: Colors.white,
                    fontSize: 15.sp,
                    fontWeight: FontWeight.w600,
                  ),
                ),
                const Spacer(),
                GestureDetector(
                  onTap: () => Navigator.pop(context),
                  child: Icon(Icons.close_rounded,
                      color: Colors.white54, size: 20.sp),
                ),
              ],
            ),
          ),
          SizedBox(height: 10.h),

          // ── Category Tab Bar ──
          SizedBox(
            height: 44.h,
            child: ListView.builder(
              scrollDirection: Axis.horizontal,
              padding: EdgeInsets.symmetric(horizontal: 12.w, vertical: 4.h),
              itemCount: widget.categories.length,
              itemBuilder: (context, i) {
                final isSelected = _selectedCategory == i;
                return GestureDetector(
                  onTap: () {
                    setState(() => _selectedCategory = i);
                    _pageController.animateToPage(
                      i,
                      duration: const Duration(milliseconds: 250),
                      curve: Curves.easeInOut,
                    );
                  },
                  child: AnimatedContainer(
                    duration: const Duration(milliseconds: 180),
                    margin: EdgeInsets.only(right: 6.w),
                    padding:
                        EdgeInsets.symmetric(horizontal: 12.w, vertical: 4.h),
                    decoration: BoxDecoration(
                      color: isSelected
                          ? Colors.white.withValues(alpha: 0.15)
                          : Colors.transparent,
                      borderRadius: BorderRadius.circular(20.r),
                      border: Border.all(
                        color: isSelected ? Colors.white30 : Colors.transparent,
                        width: 1,
                      ),
                    ),
                    child: Text(
                      widget.categories[i]['icon'] as String,
                      style: TextStyle(fontSize: 18.sp),
                    ),
                  ),
                );
              },
            ),
          ),

          Divider(color: Colors.white12, height: 1, thickness: 1),

          // ── Emoji Grid with PageView ──
          Expanded(
            child: PageView.builder(
              controller: _pageController,
              onPageChanged: (i) => setState(() => _selectedCategory = i),
              itemCount: widget.categories.length,
              itemBuilder: (context, pageIndex) {
                final emojis =
                    widget.categories[pageIndex]['emojis'] as List<String>;
                return GridView.builder(
                  padding: EdgeInsets.all(12.r),
                  itemCount: emojis.length,
                  gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(
                    crossAxisCount: 8,
                    mainAxisSpacing: 4.h,
                    crossAxisSpacing: 4.w,
                  ),
                  itemBuilder: (context, index) {
                    return _EmojiTile(
                      emoji: emojis[index],
                      onTap: () => widget.onReactionSelected(emojis[index]),
                    );
                  },
                );
              },
            ),
          ),
        ],
      ),
    );
  }
}

// ── Emoji Tile ────────────────────────────────────────────────────────────────

class _EmojiTile extends StatefulWidget {
  final String emoji;
  final VoidCallback onTap;
  const _EmojiTile({required this.emoji, required this.onTap});

  @override
  State<_EmojiTile> createState() => _EmojiTileState();
}

class _EmojiTileState extends State<_EmojiTile> {
  bool _hovered = false;

  @override
  Widget build(BuildContext context) {
    return MouseRegion(
      onEnter: (_) => setState(() => _hovered = true),
      onExit: (_) => setState(() => _hovered = false),
      cursor: SystemMouseCursors.click,
      child: GestureDetector(
        onTap: widget.onTap,
        child: AnimatedContainer(
          duration: const Duration(milliseconds: 120),
          decoration: BoxDecoration(
            color: _hovered
                ? Colors.white.withValues(alpha: 0.12)
                : Colors.transparent,
            borderRadius: BorderRadius.circular(8.r),
          ),
          alignment: Alignment.center,
          child: Text(widget.emoji, style: TextStyle(fontSize: 22.sp)),
        ),
      ),
    );
  }
}
